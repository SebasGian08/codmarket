<script>
    window.prepararIcono = function(btn) {
        window._iconoInput = btn.closest('.input-group').querySelector('input[name*="icono"]');
    };

    window.usarIcono = function(btn) {
        var clase = btn.getAttribute('data-clase');

        if (window._iconoInput) {
            window._iconoInput.value = clase;
        }

        var modal = document.getElementById('modalGuiaIconos');
        if (modal && window.bootstrap) {
            var instancia = bootstrap.Modal.getInstance(modal);
            if (instancia) {
                instancia.hide();
            }
        }

        if (window.Swal) {
            Swal.fire({
                icon: 'success',
                title: '<i class="' + clase + '"></i> &nbsp;Icono seleccionado',
                html: '<code>' + clase + '</code>',
                toast: true,
                position: 'top-end',
                showConfirmButton: false,
                timer: 2000,
                timerProgressBar: true
            });
        }
    };

    $(document).on('input', '#buscadorIconos', function() {
        var q = ($(this).val() || '').toLowerCase().trim();

        $('.guia-icono-btn').each(function() {
            var coincide = !q || (($(this).data('buscar') || '').indexOf(q) !== -1);
            $(this).closest('.col').toggle(coincide);
        });

        $('.categoria-iconos').each(function() {
            var visibles = $(this).find('.guia-icono-btn:visible').length > 0;
            $(this).toggle(visibles);
        });
    });
</script>
